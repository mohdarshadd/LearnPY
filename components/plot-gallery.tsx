import Image from "next/image";
import type { PlotOutput } from "@/lib/pyodide/protocol";

type PlotGalleryProps = {
  plots: PlotOutput[];
};

export function PlotGallery({ plots }: PlotGalleryProps) {
  return (
    <div className="grid gap-4">
      {plots.map((plot, index) => {
        const figureNumber = index + 1;
        const width = plot.width ?? 1080;
        const height = plot.height ?? 720;

        return (
          <figure
            key={index}
            className="overflow-hidden rounded-lg border border-white/10 bg-white/5"
          >
            <Image
              alt={`Figure ${figureNumber}: Matplotlib output generated by the code`}
              className="h-auto w-full bg-white"
              height={height}
              src={plot.dataUrl}
              unoptimized
              width={width}
            />
            <figcaption className="flex flex-wrap items-center justify-between gap-2 border-t border-white/10 px-3 py-2">
              <span className="font-mono text-[0.65rem] uppercase tracking-[0.12em] text-paper/45">
                Figure {figureNumber}
              </span>
              <a
                className="text-xs font-semibold text-acid hover:underline"
                download={`learnpy-figure-${figureNumber}.png`}
                href={plot.dataUrl}
              >
                Download PNG
              </a>
            </figcaption>
          </figure>
        );
      })}
    </div>
  );
}
